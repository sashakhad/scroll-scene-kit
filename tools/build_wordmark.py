#!/usr/bin/env python3
"""Build the finale wordmark paths from the bundled Caveat font.

The site ships the paths, not the font file. Caveat is SIL OFL — see
public/fonts/Caveat-OFL.txt. Re-run with `npm run wordmark` after editing WORDS.
"""

from __future__ import annotations

import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT = ROOT / "tools" / "fonts" / "Caveat-700.woff"
OUT = ROOT / "src" / "wordmark.ts"
WORDS = ("Music", "for", "Vegans")
WORD_LAG = (0.04, 0.24, 0.4)
WORD_SPAN = (0.42, 0.34, 0.46)


def glyph_path(font: TTFont, name: str, x: float, baseline: float) -> str:
    glyf = font.getGlyphSet()
    pen = SVGPathPen(glyf)
    glyf[name].draw(TransformPen(pen, (1, 0, 0, -1, x, baseline)))
    return pen.getCommands()


def flourish_paths(width: float, baseline: float) -> list[tuple[str, bool, bool, float, float]]:
    y = baseline + 150
    swoosh = (
        f"M {width * 0.06:.1f} {y:.1f} "
        f"C {width * 0.22:.1f} {y + 150:.1f}, {width * 0.4:.1f} {y - 30:.1f}, {width * 0.58:.1f} {y + 40:.1f} "
        f"S {width * 0.78:.1f} {y + 130:.1f}, {width * 0.95:.1f} {y - 20:.1f}"
    )
    leaf_x = width * 0.95
    leaf_y = y - 20
    scale = 170
    leaf = (
        f"M {leaf_x:.1f} {leaf_y:.1f} "
        f"C {leaf_x + scale * 0.35:.1f} {leaf_y - scale * 0.85:.1f}, "
        f"{leaf_x + scale * 1.05:.1f} {leaf_y - scale * 0.35:.1f}, "
        f"{leaf_x + scale * 0.15:.1f} {leaf_y + scale * 0.15:.1f} "
        f"C {leaf_x + scale * 0.55:.1f} {leaf_y + scale * 0.05:.1f}, "
        f"{leaf_x - scale * 0.1:.1f} {leaf_y + scale * 0.45:.1f}, "
        f"{leaf_x:.1f} {leaf_y:.1f}"
    )
    return [
        (swoosh, True, False, 0.58, 0.32),
        (leaf, True, True, 0.72, 0.22),
    ]


def ts_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    ascent = font["hhea"].ascent
    descent = font["hhea"].descent
    upem = font["head"].unitsPerEm
    cursor = 0.0
    word_index = 0
    paths: list[tuple[str, bool, bool, float, float]] = []

    for word in WORDS:
        lag = WORD_LAG[word_index]
        span = WORD_SPAN[word_index]
        for char in word:
            name = cmap[ord(char)]
            advance = font["hmtx"][name][0]
            data = glyph_path(font, name, cursor, float(ascent))
            if data:
                paths.append((data, False, False, lag, span))
            cursor += advance
        word_index += 1
        if word_index < len(WORDS):
            cursor += upem * 0.33

    height = float(ascent - descent)
    paths.extend(flourish_paths(cursor, float(ascent)))
    pad_x = 120
    pad_top = 80
    pad_bottom = 320
    view_w = cursor + pad_x * 2 + 220
    view_h = height + pad_top + pad_bottom
    content = render(paths, pad_x, pad_top, view_w, view_h)
    OUT.write_text(content)
    print(f"wrote {OUT} ({len(paths)} paths, view {view_w:.0f}x{view_h:.0f})")


def render(
    paths: list[tuple[str, bool, bool, float, float]],
    pad_x: float,
    pad_top: float,
    view_w: float,
    view_h: float,
) -> str:
    view = f"{-pad_x:.0f} {-pad_top:.0f} {view_w:.0f} {view_h:.0f}"
    body = [
        "// Generated by tools/build_wordmark.py from Caveat (SIL OFL).",
        "// Replace this file when you rebrand the finale signature.",
        'import type { Wordmark } from "./types.ts"',
        "",
        "export const wordmark: Wordmark = {",
        f'  viewBox: "{view}",',
        "  paths: [",
    ]
    for data, flourish, leaf, lag, span in paths:
        flags = ""
        if flourish:
            flags += ", flourish: true"
        if leaf:
            flags += ", leaf: true"
        body.append(
            "    { "
            + f"d: {ts_string(data)}, lag: {lag:.2f}, span: {span:.2f}{flags}"
            + " },"
        )
    body.append("  ],")
    body.append("}")
    body.append("")
    return "\n".join(body)


if __name__ == "__main__":
    main()
